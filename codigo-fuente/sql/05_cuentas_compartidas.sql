CREATE TABLE IF NOT EXISTS public."USUARIO_APP" (
    usuario text PRIMARY KEY CHECK (usuario ~ '^[a-z0-9_]{1,40}$'),
    nombre text NOT NULL CHECK (length(btrim(nombre)) BETWEEN 1 AND 100),
    rol text NOT NULL CHECK (rol IN ('admin', 'operador', 'cliente')),
    salt text NOT NULL CHECK (salt ~ '^[0-9a-f]{32}$'),
    hash text NOT NULL CHECK (hash ~ '^[0-9a-f]{128}$'),
    revision bigint GENERATED BY DEFAULT AS IDENTITY
);

REVOKE ALL ON public."USUARIO_APP" FROM PUBLIC;
GRANT SELECT, INSERT, UPDATE, DELETE ON public."USUARIO_APP" TO app_almacen;
GRANT USAGE, SELECT ON public."USUARIO_APP_revision_seq" TO app_almacen;
